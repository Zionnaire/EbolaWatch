/**
 * The Frontend keeps a generated copy of Backend/src/contracts/api (it never imports from ../Backend, because the
 * two folders may deploy separately). This fails when the copy has drifted: run `pnpm sync:contracts` in Frontend/.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../src/contracts/api');
const copy = path.resolve(here, '../../Frontend/src/contracts');
const HEADER =
  '// GENERATED by `pnpm sync:contracts` from Backend/src/contracts/api. DO NOT EDIT: change the Backend and sync.\n';

describe('Frontend contracts copy', () => {
  it.skipIf(!existsSync(copy))(
    'is identical to Backend/src/contracts/api (run `pnpm sync:contracts` in Frontend/)',
    () => {
      const files = readdirSync(source).filter((f) => f.endsWith('.ts'));
      expect(
        readdirSync(copy)
          .filter((f) => f.endsWith('.ts'))
          .sort(),
      ).toEqual([...files].sort());
      for (const f of files) {
        const expected = HEADER + readFileSync(path.join(source, f), 'utf8');
        // normalise line endings so a Windows checkout does not fail the comparison
        const actual = readFileSync(path.join(copy, f), 'utf8');
        expect(actual.replace(/\r\n/g, '\n'), f).toBe(expected.replace(/\r\n/g, '\n'));
      }
    },
  );
});
